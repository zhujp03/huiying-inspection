// release:prepare 的小程序运行时配置生成器。
// 从根目录 .env 只读取 MINIAPP_API_BASE_URL（公开值），生成
// apps/miniapp/miniprogram/runtime-config.generated.js。
// release/trial 必须是 https；develop 允许明确的本机地址。
// 绝不复制整个 process.env，绝不把任何 Secret 写入生成产物。
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const checkExample = process.argv.includes("--check-example");
const outputPath = resolve(root, "apps/miniapp/miniprogram/runtime-config.generated.js");

function parseDotEnv(text) {
  const result = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const match = trimmed.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    result[match[1]] = value;
  }
  return result;
}

let apiBase = "";
if (checkExample) {
  // 校验模式：用 .env.example 验证生成逻辑，不写入产物（保持仓库内为开发空值），
  // 不产生 production PASS。
  const example = readFileSync(resolve(root, ".env.example"), "utf8");
  const exampleValues = parseDotEnv(example);
  apiBase = (exampleValues.MINIAPP_API_BASE_URL || "").trim();
  if (!apiBase) {
    console.error("generate-miniapp-runtime-config: .env.example 缺少 MINIAPP_API_BASE_URL");
    process.exit(1);
  }
  console.log(`generate-miniapp-runtime-config: check-example PASS (apiBase=${apiBase}，未写入产物)`);
  process.exit(0);
}

let env = {};
try {
  const envPath = process.env.ENV_FILE || resolve(root, ".env");
  env = parseDotEnv(readFileSync(envPath, "utf8"));
} catch (error) {
  console.error(`generate-miniapp-runtime-config: 无法读取根目录 .env（${error.message}）；请先 cp .env.example .env 并填写 MINIAPP_API_BASE_URL`);
  process.exit(1);
}

apiBase = (env.MINIAPP_API_BASE_URL || "").trim();
if (!apiBase) {
  console.error("generate-miniapp-runtime-config: .env 缺少 MINIAPP_API_BASE_URL");
  process.exit(1);
}
// release/trial 必须 https；develop 允许明确的本机 http 地址（127.0.0.1/localhost）。
// 发布包安全由 release:prepare 在生成后强制 https 校验兜底。
// 额外防呆：任何形式的本机地址（含 https://localhost）都不允许进入非 development
// 配置，防止本机地址打进正式包。
function isLocalhostAddress(value) {
  try { return ["localhost", "127.0.0.1", "::1"].includes(new URL(value).hostname); }
  catch { return false; }
}
const isHttps = /^https:\/\//i.test(apiBase);
const isLocalHttp = /^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?(\/.*)?$/i.test(apiBase);
if (!isHttps && !(isLocalHttp && (env.NODE_ENV || "").trim() === "development")) {
  console.error("generate-miniapp-runtime-config: MINIAPP_API_BASE_URL 必须是 https:// 公网地址；http 仅允许本机地址且 NODE_ENV=development");
  process.exit(1);
}
if (isLocalhostAddress(apiBase)) {
  if ((env.NODE_ENV || "").trim() !== "development") {
    console.error("generate-miniapp-runtime-config: 拒绝生成——MINIAPP_API_BASE_URL 指向本机地址（localhost/127.0.0.1），发布配置不得包含本机地址；请改为 https 公网域名");
    process.exit(1);
  }
  console.log("generate-miniapp-runtime-config: 警告——MINIAPP_API_BASE_URL 是本机地址，仅限 NODE_ENV=development 本地联调，严禁用于发布包");
}
writeFileSync(outputPath, `// Generated by scripts/generate-miniapp-runtime-config.mjs — do not edit.\nexport const RUNTIME_CONFIG = Object.freeze({ apiBase: ${JSON.stringify(apiBase)} });\n`);
console.log(`generate-miniapp-runtime-config: PASS (apiBase=${apiBase})`);
